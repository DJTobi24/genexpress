//! The browser side of files, storage, fonts and the clipboard (wasm32 only).
//!
//! - Opening and placing use the browser's file picker ([`pick`]) or drag and drop; the bytes
//!   arrive a frame or two later and [`poll`] hands them to the engine (`file::open_bytes`,
//!   `image.place` with `data`, `content::quick_image_bytes`, `fonts::add_font_bytes`).
//! - Save and Download make the file's bytes and the browser downloads them ([`download`]).
//! - Data Recovery copies, recent designs and added fonts live in IndexedDB: [`open_store`]
//!   loads them before the app starts into an [`IdbStore`], the engine's
//!   [`Store`](genha_engine::store::Store), which writes changes back in the background.
//! - A picture pasted with Cmd+V comes with the page's paste event ([`install_paste`]); Edit ›
//!   Paste Picture reads the Clipboard API ([`read_clipboard_picture`]).
//! - Installed fonts, where the browser offers the Local Font Access API (Chromium), after the
//!   user asks and allows it ([`load_local_fonts`]).
//!
//! Rust calling web-sys only; the JavaScript glue is generated by wasm-bindgen.

use std::cell::{Cell, RefCell};
use std::collections::BTreeMap;

use base64::Engine as _;
use serde_json::{Value, json};
use wasm_bindgen::{JsCast as _, JsValue};
use wasm_bindgen_futures::JsFuture;

use crate::{App, Screen};
use genha_i18n::tr;

/// Largest file the browser reads for us (pictures and designs are capped lower by the engine).
const MAX_READ_BYTES: f64 = 512.0 * 1024.0 * 1024.0;
/// The IndexedDB database and object store holding the app's [`IdbStore`].
const DB_NAME: &str = "genha";
const DB_STORE: &str = "kv";
/// Most bytes of installed fonts loaded (the rest are skipped), and the largest font file.
const MAX_LOCAL_FONT_BYTES: usize = 384 << 20;
const MAX_LOCAL_FONT_FILE: f64 = 32.0 * 1024.0 * 1024.0;
/// Store key remembering that the user chose to use installed fonts.
const LOCAL_FONTS_KEY: &str = "settings/local-fonts";

/// What a file the user picked or dropped is for.
#[derive(Clone, Debug)]
pub enum Purpose {
    /// Open as a design: a `.genha` file, or a picture or SVG to start one from.
    Open,
    /// Place a picture into the open design (on the home screen: start a design from it).
    Place,
    /// "Edit a photo": a picture opened as a design, selected for the picture tools.
    Photo,
    /// "Photo collage": pictures placed into the design made for them and arranged in a grid.
    Collage,
    /// A picture from the clipboard (placed like [`Purpose::Place`]).
    Paste,
    /// A quick action on a picture; the result is downloaded as `{stem}-{action}.{ext}`.
    Quick { action: String, ext: &'static str, params: Value },
    /// A font file the user added (kept in IndexedDB).
    Font,
    /// An installed font (Local Font Access API; not kept).
    LocalFont,
}

struct Arrived {
    purpose: Purpose,
    name: String,
    bytes: Vec<u8>,
}

thread_local! {
    /// Files read and waiting for the next frame (the browser runs us on one thread).
    static ARRIVED: RefCell<Vec<Arrived>> = const { RefCell::new(Vec::new()) };
    /// Messages for the status bar from asynchronous work.
    static NOTES: RefCell<Vec<String>> = const { RefCell::new(Vec::new()) };
    /// The UI's context, to ask for a frame when a file has been read.
    static CTX: RefCell<Option<egui::Context>> = const { RefCell::new(None) };
    /// A picture is being pasted: drop the object paste of the same Cmd+V.
    static PASTING_PICTURE: Cell<bool> = const { Cell::new(false) };
    /// Whether a text field has the keyboard (then pastes are text, not pictures).
    static TYPING: Cell<bool> = const { Cell::new(false) };
    /// The open IndexedDB database.
    static DB: RefCell<Option<web_sys::IdbDatabase>> = const { RefCell::new(None) };
}

/// Seconds since 1970 (the browser's clock).
pub fn now() -> f64 {
    js_sys::Date::now() / 1000.0
}

/// The local hour (0–23), from the browser.
pub fn local_hour() -> u32 {
    js_sys::Date::new_0().get_hours().min(23)
}

/// A name for this page load's Data Recovery copies (unique enough between loads and tabs).
pub fn instance_id() -> String {
    format!("w{:x}{:04x}", js_sys::Date::now() as u64, (js_sys::Math::random() * 65535.0) as u32)
}

fn note(msg: impl Into<String>) {
    NOTES.with(|n| n.borrow_mut().push(msg.into()));
    repaint();
}

fn repaint() {
    CTX.with(|c| {
        if let Some(ctx) = &*c.borrow() {
            ctx.request_repaint();
        }
    });
}

// ---------- storage (IndexedDB) ----------

/// The engine's store in the browser: everything is loaded from IndexedDB at start
/// ([`open_store`]) and kept in memory; writes and removals go to IndexedDB in the background, in
/// order. Without IndexedDB (private windows of some browsers) it still works for this page load.
#[derive(Debug, Default)]
pub struct IdbStore {
    items: BTreeMap<String, (Vec<u8>, u64)>,
}

impl genha_engine::store::Store for IdbStore {
    fn read(&self, key: &str) -> Option<Vec<u8>> {
        self.items.get(key).map(|(b, _)| b.clone())
    }

    fn write(&mut self, key: &str, bytes: &[u8]) -> Result<(), String> {
        if !genha_engine::store::valid_key(key) {
            return Err(format!("invalid storage key `{key}`"));
        }
        let t = now() as u64;
        self.items.insert(key.to_string(), (bytes.to_vec(), t));
        let value = record(bytes, t);
        let key = key.to_string();
        wasm_bindgen_futures::spawn_local(async move {
            if let Err(e) = db_change(&key, Some(&value)).await {
                note(genha_i18n::tr!("Could not keep {key} in the browser's storage: {error}", key = key, error = e));
            }
        });
        Ok(())
    }

    fn remove(&mut self, key: &str) {
        if self.items.remove(key).is_some() {
            let key = key.to_string();
            wasm_bindgen_futures::spawn_local(async move {
                if let Err(e) = db_change(&key, None).await {
                    log::warn!("could not remove {key} from the browser's storage: {e}");
                }
            });
        }
    }

    fn list(&self, dir: &str) -> Vec<(String, u64)> {
        genha_engine::store::list_in(self.items.iter().map(|(k, (_, t))| (k.as_str(), *t)), dir)
    }

    fn locate(&self, key: &str) -> String {
        format!("browser storage: {key}")
    }
}

/// A stored value: `{b: bytes, t: seconds}`.
fn record(bytes: &[u8], t: u64) -> JsValue {
    let o = js_sys::Object::new();
    // Setting a property on a fresh plain object cannot fail.
    js_sys::Reflect::set(&o, &"b".into(), &js_sys::Uint8Array::from(bytes)).ok();
    js_sys::Reflect::set(&o, &"t".into(), &JsValue::from_f64(t as f64)).ok();
    o.into()
}

/// Waits for an IndexedDB request; its result.
async fn request(req: &web_sys::IdbRequest) -> Result<JsValue, String> {
    let promise = js_sys::Promise::new(&mut |resolve, reject| {
        req.set_onsuccess(Some(&resolve));
        req.set_onerror(Some(&reject));
    });
    JsFuture::from(promise).await.map_err(js)?;
    req.result().map_err(js)
}

/// Opens (creating on first use) the database.
async fn open_db() -> Result<web_sys::IdbDatabase, String> {
    let factory = web_sys::window().ok_or("no window")?.indexed_db().map_err(js)?.ok_or("this browser has no IndexedDB")?;
    let open = factory.open_with_u32(DB_NAME, 1).map_err(js)?;
    let upgrade = wasm_bindgen::closure::Closure::once_into_js(move |e: web_sys::Event| {
        let db = e.target().and_then(|t| t.dyn_into::<web_sys::IdbOpenDbRequest>().ok()).and_then(|r| r.result().ok());
        if let Some(db) = db.and_then(|d| d.dyn_into::<web_sys::IdbDatabase>().ok())
            && !db.object_store_names().contains(DB_STORE)
            && let Err(e) = db.create_object_store(DB_STORE)
        {
            log::error!("cannot create the browser storage: {}", js(e));
        }
    });
    open.set_onupgradeneeded(Some(upgrade.unchecked_ref()));
    let db = request(&open).await?;
    db.dyn_into::<web_sys::IdbDatabase>().map_err(|_| "not a database".to_string())
}

/// Puts (`Some`) or deletes (`None`) one record, waiting until it is stored.
async fn db_change(key: &str, value: Option<&JsValue>) -> Result<(), String> {
    let db = DB.with(|d| d.borrow().clone()).ok_or("no browser storage")?;
    let tx = db.transaction_with_str_and_mode(DB_STORE, web_sys::IdbTransactionMode::Readwrite).map_err(js)?;
    let store = tx.object_store(DB_STORE).map_err(js)?;
    match value {
        Some(v) => store.put_with_key(v, &key.into()).map_err(js)?,
        None => store.delete(&key.into()).map_err(js)?,
    };
    let done = js_sys::Promise::new(&mut |resolve, reject| {
        tx.set_oncomplete(Some(&resolve));
        tx.set_onerror(Some(&reject));
        tx.set_onabort(Some(&reject));
    });
    JsFuture::from(done).await.map_err(js)?;
    Ok(())
}

/// Every record in the database.
async fn load_all(db: &web_sys::IdbDatabase) -> Result<BTreeMap<String, (Vec<u8>, u64)>, String> {
    let tx = db.transaction_with_str(DB_STORE).map_err(js)?;
    let store = tx.object_store(DB_STORE).map_err(js)?;
    let keys = request(&store.get_all_keys().map_err(js)?).await?;
    let values = request(&store.get_all().map_err(js)?).await?;
    let (keys, values) = (js_sys::Array::from(&keys), js_sys::Array::from(&values));
    let mut out = BTreeMap::new();
    for (k, v) in keys.iter().zip(values.iter()) {
        let Some(key) = k.as_string().filter(|k| genha_engine::store::valid_key(k)) else { continue };
        let Ok(b) = js_sys::Reflect::get(&v, &"b".into()) else { continue };
        let Some(bytes) = b.dyn_ref::<js_sys::Uint8Array>().map(js_sys::Uint8Array::to_vec) else { continue };
        let t = js_sys::Reflect::get(&v, &"t".into()).ok().and_then(|t| t.as_f64()).filter(|t| t.is_finite() && *t >= 0.0).unwrap_or(0.0);
        out.insert(key, (bytes, t as u64));
    }
    Ok(out)
}

/// The app's store, loaded from IndexedDB (empty, and kept for this page load only, when the
/// browser has no IndexedDB or refuses it).
pub async fn open_store() -> Box<dyn genha_engine::store::Store> {
    let mut store = IdbStore::default();
    match open_db().await {
        Ok(db) => {
            match load_all(&db).await {
                Ok(items) => store.items = items,
                Err(e) => log::error!("cannot read the browser storage: {e}"),
            }
            DB.with(|d| *d.borrow_mut() = Some(db));
            // Ask the browser not to clear it when space runs low (it may decline).
            if let Some(Ok(p)) = web_sys::window().map(|w| w.navigator().storage().persist()) {
                wasm_bindgen_futures::spawn_local(async move {
                    // Declined is fine: the data is kept anyway unless space runs out.
                    JsFuture::from(p).await.ok();
                });
            }
        }
        Err(e) => log::error!("browser storage unavailable, nothing will be kept: {e}"),
    }
    log::info!("browser storage: {} records", store.items.len());
    Box::new(store)
}

// ---------- files ----------

/// Opens the browser's file picker for files matching `filters`; the chosen file is read and
/// handled by [`poll`] on a later frame. Cancelling does nothing. Fonts may be several files.
pub fn pick(purpose: Purpose, filters: &[(&str, &[&str])]) {
    if let Err(e) = start_picker(purpose, filters) {
        log::error!("file picker: {e}");
    }
}

fn start_picker(purpose: Purpose, filters: &[(&str, &[&str])]) -> Result<(), String> {
    let document = web_sys::window().and_then(|w| w.document()).ok_or("no document")?;
    let input: web_sys::HtmlInputElement = document.create_element("input").map_err(js)?.dyn_into().map_err(|_| "not an input element")?;
    input.set_type("file");
    input.set_multiple(matches!(purpose, Purpose::Font | Purpose::Collage));
    let accept: Vec<String> = filters.iter().flat_map(|(_, exts)| exts.iter().map(|e| format!(".{e}"))).collect();
    input.set_accept(&accept.join(","));
    let chosen = input.clone();
    // Called once when files are chosen (a cancelled picker never calls it; the browser then
    // drops the input and this closure with it).
    let on_change = wasm_bindgen::closure::Closure::once_into_js(move || {
        let Some(files) = chosen.files() else { return };
        for i in 0..files.length() {
            if let Some(file) = files.get(i) {
                read_file(purpose.clone(), file);
            }
        }
    });
    input.set_onchange(Some(on_change.unchecked_ref()));
    // The click that asked for the picker is still being handled (eframe runs the frame inside
    // the pointer event), so the browser lets the page open it.
    input.click();
    Ok(())
}

/// Reads `file` and hands it to [`poll`].
fn read_file(purpose: Purpose, file: web_sys::File) {
    wasm_bindgen_futures::spawn_local(async move {
        let name = file.name();
        if file.size() > MAX_READ_BYTES {
            note(format!("{name} is too large to open in the browser"));
            return;
        }
        match JsFuture::from(file.array_buffer()).await {
            Ok(buf) => arrive(purpose, name, js_sys::Uint8Array::new(&buf).to_vec()),
            Err(e) => note(format!("cannot read {name}: {}", js(e))),
        }
    });
}

fn arrive(purpose: Purpose, name: String, bytes: Vec<u8>) {
    ARRIVED.with(|a| a.borrow_mut().push(Arrived { purpose, name, bytes }));
    repaint();
}

/// Called once per frame: starts reading dropped files and hands files that have been read to
/// the engine.
pub fn poll(app: &mut App, ctx: &egui::Context) {
    let first = CTX.with(|c| {
        let mut c = c.borrow_mut();
        let first = c.is_none();
        if first {
            *c = Some(ctx.clone());
        }
        first
    });
    if first {
        install_paste();
        if app.session.store.as_ref().is_some_and(|s| s.read(LOCAL_FONTS_KEY).is_some()) {
            load_local_fonts(false);
        }
    }
    TYPING.with(|t| t.set(ctx.egui_wants_keyboard_input() || app.session.text_editing.is_some()));
    // A picture is being pasted: the same Cmd+V must not also paste copied objects.
    if PASTING_PICTURE.with(|p| p.replace(false)) {
        ctx.input_mut(|i| i.consume_key(egui::Modifiers::COMMAND, egui::Key::V));
    }
    let dropped = ctx.input_mut(|i| std::mem::take(&mut i.raw.dropped_files));
    for f in dropped {
        let name = f.path().file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_else(|| "dropped".into());
        let ext = std::path::Path::new(&name).extension().and_then(|e| e.to_str()).unwrap_or("").to_ascii_lowercase();
        let is_picture = genha_effects::OutputFormat::from_extension(&ext).is_some() || ext == "svg";
        let purpose = if is_picture {
            Purpose::Place
        } else if crate::fonts::FONT_FILES.1.contains(&ext.as_str()) {
            Purpose::Font
        } else {
            Purpose::Open
        };
        wasm_bindgen_futures::spawn_local(async move {
            match f.bytes_async().await {
                Ok(bytes) => arrive(purpose, name, bytes),
                Err(e) => note(format!("cannot read {name}: {e}")),
            }
        });
    }
    let arrived = ARRIVED.with(|a| std::mem::take(&mut *a.borrow_mut()));
    let mut fonts_added = false;
    let mut local_faces = 0;
    for a in arrived {
        match a.purpose {
            Purpose::Font | Purpose::LocalFont => {
                let local = matches!(a.purpose, Purpose::LocalFont);
                match genha_engine::cmd::fonts::add_font_bytes(&mut app.session, &a.name, a.bytes, !local) {
                    Ok((faces, families)) => {
                        fonts_added = true;
                        if local {
                            local_faces += faces;
                        } else {
                            app.set_status(genha_i18n::tr!("Added {fonts}", fonts = if families.is_empty() { a.name } else { families.join(", ") }));
                        }
                    }
                    // A broken installed font is not worth a message.
                    Err(e) if local => log::warn!("{e}"),
                    Err(e) => app.set_status(e.to_string()),
                }
            }
            _ => handle(app, a),
        }
    }
    if fonts_added {
        app.refresh_fonts();
    }
    if local_faces > 0 {
        app.set_status(genha_i18n::tr_n!("Added {n} installed font face", "Added {n} installed font faces", local_faces));
    }
    if REMEMBER_LOCAL.with(|r| r.replace(false))
        && let Some(store) = app.session.store.as_mut()
        && store.read(LOCAL_FONTS_KEY).is_none()
        && let Err(e) = store.write(LOCAL_FONTS_KEY, b"1")
    {
        log::warn!("{e}");
    }
    for n in NOTES.with(|n| std::mem::take(&mut *n.borrow_mut())) {
        app.set_status(n);
    }
}

fn handle(app: &mut App, a: Arrived) {
    match a.purpose {
        Purpose::Paste => crate::clipboard::place(app, &a.bytes),
        Purpose::Place if app.screen == Screen::Editor && app.session.active().is_some() => {
            let data = base64::engine::general_purpose::STANDARD.encode(&a.bytes);
            app.run("image.place", &json!({"data": data, "name": a.name}));
        }
        Purpose::Collage => {
            if app.session.active().is_some() {
                let data = base64::engine::general_purpose::STANDARD.encode(&a.bytes);
                if app.run("image.place", &json!({"data": data, "name": a.name})).is_some() {
                    crate::home::arrange_collage(app);
                }
            }
        }
        Purpose::Open if crate::fonts::FONT_FILES.1.iter().any(|f| a.name.to_ascii_lowercase().ends_with(&format!(".{f}"))) => {
            match genha_engine::cmd::fonts::add_font_bytes(&mut app.session, &a.name, a.bytes, true) {
                Ok((_, families)) => {
                    app.refresh_fonts();
                    app.set_status(genha_i18n::tr!("Added {fonts}", fonts = if families.is_empty() { a.name } else { families.join(", ") }));
                }
                Err(e) => app.set_status(e.to_string()),
            }
        }
        Purpose::Open | Purpose::Place | Purpose::Photo => match genha_engine::cmd::file::open_bytes(&mut app.session, &a.name, &a.bytes) {
            Ok(_) => {
                app.screen = Screen::Editor;
                app.view.fit_pending = true;
                app.refresh_library();
                if matches!(a.purpose, Purpose::Photo) {
                    crate::home::select_picture(app);
                }
            }
            Err(e) => app.set_status(e.to_string()),
        },
        Purpose::Quick { action, ext, params } => match genha_engine::cmd::content::quick_image_bytes(&a.bytes, ext, &params) {
            Ok((data, ..)) => {
                let stem = std::path::Path::new(&a.name).file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_else(|| "picture".into());
                finish(app, &format!("{stem}-{action}.{ext}"), &data);
            }
            Err(e) => app.set_status(e.to_string()),
        },
        // Fonts are handled in `poll`.
        Purpose::Font | Purpose::LocalFont => {}
    }
}

/// A Download menu entry in the browser: the export command `cmd`'s file, made in memory with
/// `params` and downloaded as `{stem}.{ext}`.
pub fn export(app: &mut App, cmd: &str, ext: &str, params: &Value, stem: &str) {
    use genha_engine::cmd::export::{Format, page_bytes, pdf_bytes};
    use genha_engine::cmd::motion::{Animated, animated_bytes, video_bytes};
    let page = app.session.active().map(|d| d.page).unwrap_or(0);
    let bytes = match cmd {
        "export.png" => page_bytes(&app.session, page, Format::Png, params),
        "export.jpeg" => page_bytes(&app.session, page, Format::Jpeg, params),
        "export.svg" => page_bytes(&app.session, page, Format::Svg, params),
        "export.pdf" => pdf_bytes(&app.session, params),
        "export.gif" => animated_bytes(&app.session, params, Animated::Gif).map(|(b, _)| b),
        "export.apng" => animated_bytes(&app.session, params, Animated::Apng).map(|(b, _)| b),
        // In the browser the video is made in place (no threads there): the page waits for it.
        "export.mp4" => match app.session.doc() {
            Ok(d) => video_bytes(&d.doc, &app.session.fonts, d.page, params, &mut |_, _| true).map(|(b, _)| b),
            Err(e) => Err(e),
        },
        other => {
            app.set_status(format!("{other} is not available in the browser yet"));
            return;
        }
    };
    match bytes {
        Ok(b) => finish(app, &format!("{stem}.{ext}"), &b),
        Err(e) => app.set_status(e.to_string()),
    }
}

/// Save in the browser: the design's `.genha` file is downloaded (and the design marked saved,
/// and kept in the recent designs).
pub fn save(app: &mut App, stem: &str) {
    match genha_engine::cmd::file::design_bytes(&mut app.session) {
        Ok(b) => {
            app.refresh_library();

            finish(app, &format!("{stem}.genha"), &b);
        }
        Err(e) => app.set_status(e.to_string()),
    }
}

fn finish(app: &mut App, name: &str, bytes: &[u8]) {
    match download(name, bytes) {
        Ok(()) => app.set_status(genha_i18n::tr!("Downloaded {path}", path = name)),
        Err(e) => app.set_status(genha_i18n::tr!("Could not download {name}: {error}", name = name, error = e)),
    }
}

/// Has the browser download `bytes` as a file called `name`.
pub fn download(name: &str, bytes: &[u8]) -> Result<(), String> {
    let window = web_sys::window().ok_or("no window")?;
    let document = window.document().ok_or("no document")?;
    let parts = js_sys::Array::of1(&js_sys::Uint8Array::from(bytes));
    let opts = web_sys::BlobPropertyBag::new();
    opts.set_type(mime(name));
    let blob = web_sys::Blob::new_with_u8_array_sequence_and_options(&parts, &opts).map_err(js)?;
    let url = web_sys::Url::create_object_url_with_blob(&blob).map_err(js)?;
    let a: web_sys::HtmlAnchorElement = document.create_element("a").map_err(js)?.dyn_into().map_err(|_| "not an anchor element")?;
    a.set_href(&url);
    a.set_download(name);
    a.style().set_property("display", "none").map_err(js)?;
    let body = document.body().ok_or("no document body")?;
    body.append_child(&a).map_err(js)?;
    a.click();
    a.remove();
    // Let go of the blob once the download has started (it keeps its own reference).
    let revoke = wasm_bindgen::closure::Closure::once_into_js(move || {
        // Nothing to do if it fails: the page just keeps the blob a little longer.
        web_sys::Url::revoke_object_url(&url).ok();
    });
    window.set_timeout_with_callback_and_timeout_and_arguments_0(revoke.unchecked_ref(), 30_000).map_err(js)?;
    Ok(())
}

fn mime(name: &str) -> &'static str {
    let ext = std::path::Path::new(name).extension().and_then(|e| e.to_str()).unwrap_or("").to_ascii_lowercase();
    match ext.as_str() {
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "webp" => "image/webp",
        "gif" => "image/gif",
        "bmp" => "image/bmp",
        "svg" => "image/svg+xml",
        "pdf" => "application/pdf",
        "mp4" => "video/mp4",
        _ => "application/octet-stream",
    }
}

// ---------- clipboard ----------

/// Listens for the page's paste events: a picture among the pasted files is read and placed.
fn install_paste() {
    let Some(document) = web_sys::window().and_then(|w| w.document()) else { return };
    let on_paste = wasm_bindgen::closure::Closure::<dyn FnMut(web_sys::ClipboardEvent)>::new(|e: web_sys::ClipboardEvent| {
        if TYPING.with(Cell::get) {
            return; // text pasted into a text field
        }
        let Some(files) = e.clipboard_data().and_then(|d| d.files()) else { return };
        let mut found = false;
        for i in 0..files.length() {
            if let Some(f) = files.get(i)
                && f.type_().starts_with("image/")
            {
                found = true;
                read_file(Purpose::Paste, f);
                break;
            }
        }
        if found {
            PASTING_PICTURE.with(|p| p.set(true));
            e.prevent_default();
            repaint();
        }
    });
    if let Err(e) = document.add_event_listener_with_callback("paste", on_paste.as_ref().unchecked_ref()) {
        log::error!("cannot listen for pastes: {}", js(e));
    }
    // Listens for the page's lifetime.
    on_paste.forget();
}

/// Edit › Paste Picture: reads a picture from the Clipboard API (the browser may ask the user).
pub fn read_clipboard_picture() {
    wasm_bindgen_futures::spawn_local(async {
        match clipboard_picture().await {
            Ok(Some(bytes)) => arrive(Purpose::Paste, tr("Pasted picture").into(), bytes),
            Ok(None) => note(tr("There is no picture on the clipboard")),
            Err(e) => note(genha_i18n::tr!("Could not read the clipboard: {error} (paste with Ctrl+V instead)", error = e)),
        }
    });
}

async fn clipboard_picture() -> Result<Option<Vec<u8>>, String> {
    let clipboard = web_sys::window().ok_or("no window")?.navigator().clipboard();
    let items = js_sys::Array::from(&JsFuture::from(clipboard.read()).await.map_err(js)?);
    for item in items.iter() {
        let Ok(item) = item.dyn_into::<web_sys::ClipboardItem>() else { continue };
        let Some(ty) = item.types().iter().filter_map(|t| t.as_string()).find(|t| t.starts_with("image/")) else { continue };
        let blob: web_sys::Blob = JsFuture::from(item.get_type(&ty)).await.map_err(js)?.dyn_into().map_err(|_| "not a blob")?;
        if blob.size() > MAX_READ_BYTES {
            return Err("the picture is too large".into());
        }
        let buf = JsFuture::from(blob.array_buffer()).await.map_err(js)?;
        return Ok(Some(js_sys::Uint8Array::new(&buf).to_vec()));
    }
    Ok(None)
}

// ---------- installed fonts (Local Font Access API) ----------

fn query_local_fonts_fn() -> Option<js_sys::Function> {
    let window = web_sys::window()?;
    js_sys::Reflect::get(&window, &"queryLocalFonts".into()).ok()?.dyn_into::<js_sys::Function>().ok()
}

/// Whether this browser can give pages the installed fonts (Chromium's Local Font Access API).
pub fn local_fonts_supported() -> bool {
    query_local_fonts_fn().is_some()
}

/// Loads the installed fonts (after the browser asks the user, the first time). `asked`: the user
/// clicked for it now (else: at start, because they did before).
pub fn load_local_fonts(asked: bool) {
    wasm_bindgen_futures::spawn_local(async move {
        match local_fonts().await {
            Ok(0) => note(tr("No installed fonts were found")),
            Ok(_) => {}
            Err(e) if asked => note(genha_i18n::tr!("Installed fonts are not available: {error}", error = e)),
            Err(e) => log::warn!("installed fonts: {e}"),
        }
    });
}

/// Reads every installed font file (each once, largest files and past the budget skipped).
async fn local_fonts() -> Result<usize, String> {
    let query = query_local_fonts_fn().ok_or("this browser can't share installed fonts")?;
    let window = web_sys::window().ok_or("no window")?;
    let promise: js_sys::Promise = query.call0(&window).map_err(js)?.dyn_into().map_err(|_| "not a promise")?;
    let fonts = js_sys::Array::from(&JsFuture::from(promise).await.map_err(js)?);
    let mut total = 0usize;
    let mut seen_files = std::collections::HashSet::new();
    let mut batch: Vec<Arrived> = vec![];
    for fd in fonts.iter() {
        let get = |k: &str| js_sys::Reflect::get(&fd, &k.into()).ok().and_then(|v| v.as_string()).unwrap_or_default();
        let (postscript, full) = (get("postscriptName"), get("fullName"));
        let Some(blob_fn) = js_sys::Reflect::get(&fd, &"blob".into()).ok().and_then(|f| f.dyn_into::<js_sys::Function>().ok()) else { continue };
        let Ok(p) = blob_fn.call0(&fd).and_then(|p| p.dyn_into::<js_sys::Promise>()) else { continue };
        let Ok(blob) = JsFuture::from(p).await.and_then(|b| b.dyn_into::<web_sys::Blob>()) else { continue };
        let size = blob.size();
        if size > MAX_LOCAL_FONT_FILE || total.saturating_add(size as usize) > MAX_LOCAL_FONT_BYTES {
            continue;
        }
        let Ok(buf) = JsFuture::from(blob.array_buffer()).await else { continue };
        let bytes = js_sys::Uint8Array::new(&buf).to_vec();
        // Faces of one collection come as several entries with the same file.
        let fingerprint = (bytes.len(), bytes.iter().take(4096).fold(0u64, |h, b| h.wrapping_mul(31).wrapping_add(u64::from(*b))));
        if !seen_files.insert(fingerprint) {
            continue;
        }
        total += bytes.len();
        batch.push(Arrived { purpose: Purpose::LocalFont, name: if full.is_empty() { postscript } else { full }, bytes });
    }
    // Next time, load them at start without asking (`poll` keeps the choice).
    // All at once: the fonts are added (and text drawn again) in one frame.
    let n = batch.len();
    ARRIVED.with(|a| a.borrow_mut().extend(batch));
    REMEMBER_LOCAL.with(|r| r.set(n > 0));
    repaint();
    Ok(n)
}

thread_local! {
    /// Installed fonts were loaded: remember the choice for next time.
    static REMEMBER_LOCAL: Cell<bool> = const { Cell::new(false) };
}

fn js(e: JsValue) -> String {
    e.as_string().or_else(|| js_sys::Reflect::get(&e, &"message".into()).ok().and_then(|m| m.as_string())).unwrap_or_else(|| format!("{e:?}"))
}
